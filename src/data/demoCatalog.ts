function photo(id: string, width = 900): string {
  return `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${width}&q=80`
}

function images(ids: string[]): ProductImage[] {
  return ids.map((id, order) => ({ url: photo(id), path: '', order }))
}

